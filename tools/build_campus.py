"""Convert the OpenStreetMap extract of the HCMUT campus (osm-campus.json, data
(c) OpenStreetMap contributors, ODbL) into game coordinates: meters, rotated so the
street grid is axis aligned, scaled for a ~10 player match. Writes js/campus-data.js."""
import json, math, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SCALE = 0.7
ROT = 29  # degrees: aligns the dominant 61° street grid with the X axis
d = json.load(open(os.path.join(HERE, 'osm-campus.json')))
camp = [e for e in d['elements'] if e['id'] == 237665212][0]
lat0 = sum(p['lat'] for p in camp['geometry']) / len(camp['geometry'])
lon0 = sum(p['lon'] for p in camp['geometry']) / len(camp['geometry'])
R = 6378137
ca, sa = math.cos(math.radians(ROT)), math.sin(math.radians(ROT))
def xy(p):
    x = (p['lon'] - lon0) * math.pi / 180 * R * math.cos(lat0 * math.pi / 180)
    z = -(p['lat'] - lat0) * math.pi / 180 * R
    return ((x * ca - z * sa) * SCALE, (x * sa + z * ca) * SCALE)
def area(P): return 0.5 * sum(P[i][0] * P[(i + 1) % len(P)][1] - P[(i + 1) % len(P)][0] * P[i][1] for i in range(len(P)))
def clean(P, tol_deg=6, min_len=0.6):
    if P[0] == P[-1] or math.dist(P[0], P[-1]) < 1e-6: P = P[:-1]
    changed = True
    while changed and len(P) > 3:
        changed = False
        for i in range(len(P)):
            a, b, c = P[i - 1], P[i], P[(i + 1) % len(P)]
            if math.dist(a, b) < min_len:
                P = P[:i] + P[i + 1:]; changed = True; break
            v1 = (b[0] - a[0], b[1] - a[1]); v2 = (c[0] - b[0], c[1] - b[1])
            cr = v1[0] * v2[1] - v1[1] * v2[0]; dt = v1[0] * v2[0] + v1[1] * v2[1]
            if abs(math.degrees(math.atan2(cr, dt))) < tol_deg:
                P = P[:i] + P[i + 1:]; changed = True; break
    if area(P) < 0: P = P[::-1]
    return [[round(x, 2), round(z, 2)] for x, z in P]
B = clean([xy(p) for p in camp['geometry']], 3, 1.0)
def inside(x, z, P=B):
    c = False
    for i in range(len(P)):
        x1, z1 = P[i]; x2, z2 = P[(i + 1) % len(P)]
        if (z1 > z) != (z2 > z) and x < (x2 - x1) * (z - z1) / (z2 - z1) + x1: c = not c
    return c
xs = [p[0] for p in B]; zs = [p[1] for p in B]
bbox = [min(xs), min(zs), max(xs), max(zs)]
buildings, roads, pitches, outside = [], [], [], []
W = {'primary': 14, 'primary_link': 8, 'secondary': 12, 'secondary_link': 7, 'tertiary': 9, 'residential': 6, 'unclassified': 6, 'service': 4.5, 'pedestrian': 4, 'footway': 2.2}
for e in d['elements']:
    t = e.get('tags', {}); g = e.get('geometry')
    if not g or e['id'] == 237665212: continue
    pts = [xy(p) for p in g]
    cx = sum(p[0] for p in pts) / len(pts); cz = sum(p[1] for p in pts) / len(pts)
    if 'building' in t and len(pts) >= 4:
        P = clean(pts)
        if len(P) < 3 or abs(area(P)) < 12: continue
        lv = t.get('building:levels')
        rec = {'n': (t.get('name') or t.get('ref') or '').replace('Nhà ', ''), 'lv': int(float(lv)) if lv else None, 'p': P}
        (buildings if inside(cx, cz) else outside).append(rec)
    elif 'leisure' in t and t['leisure'] in ('pitch', 'track', 'park', 'garden') and inside(cx, cz):
        pitches.append({'s': t.get('sport', t['leisure']), 'p': clean(pts, 3, 0.5)})
    elif 'highway' in t and t['highway'] in W:
        if not any(bbox[0] - 90 < x < bbox[2] + 90 and bbox[1] - 90 < z < bbox[3] + 90 for x, z in pts): continue
        roads.append({'k': t['highway'], 'w': round(W[t['highway']] * (SCALE if t['highway'] in ('service', 'footway', 'pedestrian') else 0.85), 2),
                      'in': 1 if inside(cx, cz) else 0, 'p': [[round(x, 2), round(z, 2)] for x, z in pts]})
out = {'source': 'OpenStreetMap contributors (ODbL)', 'scale': SCALE, 'boundary': B, 'bbox': [round(v, 2) for v in bbox],
       'buildings': buildings, 'outside': outside, 'roads': roads, 'pitches': pitches}
dst = os.path.join(HERE, '..', 'js', 'campus-data.js')
with open(dst, 'w') as f:
    f.write('// Generated by tools/build_campus.py from OpenStreetMap data (c) OpenStreetMap contributors, ODbL 1.0.\n')
    f.write('export default ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('bbox', bbox, 'buildings', len(buildings), 'outside', len(outside), 'roads', len(roads), 'pitches', len(pitches), 'boundary pts', len(B))
for b in buildings: print(b['n'], b['lv'], len(b['p']), round(abs(area(b['p']))))
for p in pitches: print('pitch', p['s'], round(abs(area(p['p']))), [round(sum(q[0] for q in p['p'])/len(p['p'])), round(sum(q[1] for q in p['p'])/len(p['p']))])
